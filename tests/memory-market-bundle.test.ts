import test from 'node:test';
import assert from 'node:assert/strict';
import {existsSync,mkdirSync,mkdtempSync,readFileSync,rmSync} from 'node:fs';
import {dirname,join,resolve,sep} from 'node:path';
import {pathToFileURL} from 'node:url';
import {spawnSync} from 'node:child_process';
import Loader,{interpolate} from '@deepseek-ai/cordis-plugin-loader';
import {entryListSchema,applyEntryPatches,type PatchOptions} from '@deepseek-ai/cordis-plugin-include';
import {load} from 'js-yaml';
import {createAgentRuntime} from './fixtures/runtime/agent-runtime.ts';

test('the actual npm archive is a loadable DSH bundle with profile-local storage',{timeout:30000},async t=>{
  const root=resolve('.');
  const pkg=existsSync(join(root,'cordis.patch.yml'))?root:join(root,'packages/dsh-companion-memory');
  const manifest=JSON.parse(readFileSync(join(pkg,'package.json'),'utf8'));
  assert.equal(manifest.dsh.bundle.patch,'./cordis.patch.yml');
  assert.equal(manifest.engines.dsh,'0.2.1-rc.2');
  const temporaryBase=join(root,'.runtime');mkdirSync(temporaryBase,{recursive:true});
  const directory=mkdtempSync(join(temporaryBase,'market-package-'));
  let cleanupRuntime=async()=>{};
  t.after(async()=>{await cleanupRuntime();assert.ok(directory.startsWith(temporaryBase+sep));rmSync(directory,{recursive:true,force:true});});
  const tsc=join(root,'node_modules/typescript/bin/tsc');
  const compile=spawnSync(process.execPath,[tsc,'-p',join(pkg,'tsconfig.build.json')],{encoding:'utf8'});
  assert.equal(compile.status,0,compile.stdout+compile.stderr);
  const npm=process.env.npm_execpath;
  assert.ok(npm,'Run the package test through npm test or npm run check');
  const packed=spawnSync(process.execPath,[npm,'pack',pkg,'--json','--pack-destination',directory],{encoding:'utf8'});
  assert.equal(packed.status,0,packed.stderr);
  const archive=join(directory,JSON.parse(packed.stdout)[0].filename);
  const listing=spawnSync('tar',['-tzf',archive],{encoding:'utf8'});assert.equal(listing.status,0,listing.stderr);
  const files=listing.stdout.trim().split(/\r?\n/);
  assert.ok(files.every(f=>f.startsWith('package/')&&!f.split('/').includes('..')));
  assert.ok(files.every(f=>!/(^|\/)(\.env|state\.sqlite|channels\.json|token-budget\.json)(\/|$)/.test(f)));
  const extracted=spawnSync('tar',['-xzf',archive,'-C',directory],{encoding:'utf8'});assert.equal(extracted.status,0,extracted.stderr);
  const packageRoot=join(directory,'package');
  const actual=JSON.parse(readFileSync(join(packageRoot,'package.json'),'utf8'));
  assert.equal(actual.version,manifest.version);
  const patches=load(readFileSync(join(packageRoot,actual.dsh.bundle.patch),'utf8'),{schema:entryListSchema}) as PatchOptions[];
  const rows=applyEntryPatches([],patches,()=>{throw new Error('Bundle patch did not apply');});
  assert.equal(rows.length,1);assert.equal(rows[0]!.name,manifest.name);
  const runtime=await createAgentRuntime();let mount:Awaited<ReturnType<typeof runtime.root.plugin>>|undefined;
  cleanupRuntime=async()=>{await mount?.dispose();await runtime.dispose();};
  const profile=join(directory,'profile');mkdirSync(profile,{recursive:true});
  runtime.root.provide('profileContext',{name:'market-test',dir:profile,patchPath:join(profile,'cordis.patch.yml'),installAnchor:join(root,'package.json'),cwd:root,home:directory,startedBundles:[],overlays:[],telemetryDisabledEnv:'1'});
  assert.equal(interpolate(runtime.root,rows[0]!.disabled),false);
  const config=interpolate(runtime.root,rows[0]!.config);
  assert.equal(resolve(config.dataDir),join(profile,'companion-memory'));
  mount=await runtime.root.plugin(Loader,{baseUrl:pathToFileURL(root+sep).href});
  const id=await runtime.root.loader.create({...rows[0]!,name:pathToFileURL(join(packageRoot,actual.main)).href,config:{...config,idleReviewSeconds:0}});
  await runtime.root.loader.await();
  const entry=runtime.root.loader.resolve(id);
  assert.ok(entry.fiber);
  await entry.fiber.await();
  assert.ok(existsSync(join(profile,'companion-memory/companion-memory.sqlite')));
  assert.deepEqual(runtime.root.companionMemory.userProfile().entries,[]);
  const agent=await runtime.createAgent('market-agent');
  assert.ok(runtime.root.tools.schemas(agent.agent).some(tool=>tool.name==='read_memory'));
  await agent.dispose();runtime.root.loader.remove(id);await runtime.root.loader.await();
});
